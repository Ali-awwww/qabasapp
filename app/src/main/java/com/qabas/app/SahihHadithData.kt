/**
 * نموذج الربط القرآني للحديث النبوي الشريف (تآخي الوحيين: الكتاب والسنة)
 */
@Immutable
data class QuranicEvidence(
    val surahName: String,                               // اسم السورة (مثل: سورة البينة)
    val ayahNumber: Int,                                 // رقم الآية الكريمة
    val verseText: String,                               // الآية الكريمة مضبوطة بالرسم العثماني
    val relationType: String,                            // نوع الربط (تأصيل قرآني، تفسير وتبيين، جزاء ووعد)
    val commentary: String = "",                         // البيان والشرح
    val surahNumber: Int = 0,                            // رقم السورة في المصحف الشريف
    val relationExplanation: String = commentary,        // وجه الدلالة والتكامل
    val tafsirSummary: String? = null                    // ومضة تفسيرية
)

