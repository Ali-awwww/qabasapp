    fun getAllHadiths(): List<SahihHadithItem> = bukhariHadiths + muslimHadiths

    fun getHadithsForBook(bookType: SahihBookType): List<SahihHadithItem> {
        return when (bookType) {
            SahihBookType.BUKHARI -> bukhariHadiths
            SahihBookType.MUSLIM -> muslimHadiths
        }
    }

    fun getChaptersForBook(bookType: SahihBookType): List<Pair<String, String>> {
        val hadiths = getHadithsForBook(bookType)
        return hadiths.map { it.chapterId to it.chapterTitle }.distinctBy { it.first }
    }

    fun getHadithsWithQuranEvidence(bookType: SahihBookType? = null): List<SahihHadithItem> {
        val baseList = if (bookType != null) getHadithsForBook(bookType) else getAllHadiths()
        return baseList.filter { it.quranEvidence != null }
    }

    fun searchHadiths(
        bookType: SahihBookType?,
        chapterId: String?,
        query: String
    ): List<SahihHadithItem> {
        val baseList = if (bookType != null) getHadithsForBook(bookType) else getAllHadiths()
        val trimmedQuery = query.trim()
        return baseList.filter { hadith ->
            val matchChapter = chapterId.isNullOrEmpty() || hadith.chapterId == chapterId
            val quranMatch = hadith.quranEvidence?.let { qe ->
                qe.verseText.contains(trimmedQuery, ignoreCase = true) ||
                        qe.surahName.contains(trimmedQuery, ignoreCase = true) ||
                        qe.relationType.contains(trimmedQuery, ignoreCase = true) ||
                        qe.commentary.contains(trimmedQuery, ignoreCase = true)
            } ?: false
            val matchQuery = trimmedQuery.isEmpty() ||
                    hadith.title.contains(trimmedQuery, ignoreCase = true) ||
                    hadith.matn.contains(trimmedQuery, ignoreCase = true) ||
                    hadith.narrator.contains(trimmedQuery, ignoreCase = true) ||
                    hadith.explanation.contains(trimmedQuery, ignoreCase = true) ||
                    hadith.wisdomCapsule.contains(trimmedQuery, ignoreCase = true) ||
                    hadith.hadithNumber.toString() == trimmedQuery ||
                    hadith.tags.any { it.contains(trimmedQuery, ignoreCase = true) } ||
                    quranMatch
            matchChapter && matchQuery
        }
    }

    fun getHadithById(id: String): SahihHadithItem? {
        return bukhariHadiths.find { it.id == id } ?: muslimHadiths.find { it.id == id }
    }

    fun getRandomDailyHadith(): SahihHadithItem {
        val all = getAllHadiths()
        val dayOfYear = java.util.Calendar.getInstance().get(java.util.Calendar.DAY_OF_YEAR)
        return all[dayOfYear % all.size]
    }

    // Bookmarking helpers (using SharedPreferences for durable zero-overhead local storage)
    private const val PREFS_NAME = "qabas_sahih_bookmarks"
    private const val KEY_BOOKMARKS = "saved_hadith_ids"

    fun isBookmarked(context: Context, hadithId: String): Boolean {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val set = prefs.getStringSet(KEY_BOOKMARKS, emptySet()) ?: emptySet()
        return set.contains(hadithId)
    }

    fun toggleBookmark(context: Context, hadithId: String): Boolean {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val currentSet = prefs.getStringSet(KEY_BOOKMARKS, emptySet())?.toMutableSet() ?: mutableSetOf()
        val willBookmark = !currentSet.contains(hadithId)
        if (willBookmark) {
            currentSet.add(hadithId)
        } else {
            currentSet.remove(hadithId)
        }
        prefs.edit().putStringSet(KEY_BOOKMARKS, currentSet).apply()
        return willBookmark
    }

    fun getBookmarkedHadiths(context: Context): List<SahihHadithItem> {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val set = prefs.getStringSet(KEY_BOOKMARKS, emptySet()) ?: emptySet()
        return getAllHadiths().filter { set.contains(it.id) }
    }

    // =========================================================================
    // 🔄 تحويل الأحاديث إلى بنية IslamicBook (للتكامل التام مع المكتبة الإسلامية)
    // =========================================================================

    fun toBookSection(hadith: SahihHadithItem): BookSection {
        val quranSection = hadith.quranEvidence?.let { qe ->
            """
• الدليل القرآني وتوافق الوحيين:
📖 [${qe.surahName} - آية ${qe.ayahNumber}]:
« ${qe.verseText} »
• وجه الدلالة والتكامل: ${qe.relationType}
• البيان: ${qe.commentary}
"""
        } ?: ""

        return BookSection(
            id = hadith.id,
            sectionTitle = "الحديث (${hadith.hadithNumber}): ${hadith.title}",
            content = """${hadith.narrator}:
${hadith.matn}

[${hadith.reference}]
$quranSection
• الشرح والبيان:
${hadith.explanation}

• الفوائد والضوابط العملية:
${hadith.practicalBenefits.joinToString(separator = "\n") { "✔ $it" }}""",
            keyRuleOrBenefit = hadith.practicalBenefits.firstOrNull() ?: "",
            wisdomCapsule = hadith.wisdomCapsule,
            references = hadith.reference,
            readTimeMinutes = 3,
            tags = hadith.tags,
            quiz = hadith.quiz
        )
    }

    fun createIslamicBookForSahih(bookType: SahihBookType): IslamicBook {
        val hadiths = getHadithsForBook(bookType)
        val groupedChapters = hadiths.groupBy { it.chapterId to it.chapterTitle }
        val chapters = groupedChapters.map { (key, list) ->
            BookChapter(
                id = key.first,
                chapterTitle = key.second,
                sections = list.map { toBookSection(it) }
            )
        }
        return IslamicBook(
            id = bookType.id,
            title = "${bookType.titleAr} (${bookType.subtitle.take(30)}...)",
            authorId = if (bookType == SahihBookType.BUKHARI) "al_bukhari" else "muslim",
            authorName = bookType.authorAr,
            category = "الصحيحان (البخاري ومسلم)",
            levelBadge = bookType.badge,
            description = "${bookType.subtitle}. ${bookType.quote}",
            scholarQuote = bookType.quote,
            hookTitle = "كيف جمع ${bookType.authorShort} عيون السنن النبوية الصحيحة بأعلى درجات التوثيق والورع؟",
            totalEstimatedMinutes = 45,
            chapters = chapters
        )
    }
