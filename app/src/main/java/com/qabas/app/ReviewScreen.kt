                    Spacer(modifier = Modifier.width(8.dp))
                    Text(Translator.tr("ممتاز"), fontFamily = CairoFont, fontWeight = FontWeight.Bold)
                }
                
                OutlinedButton(
                    onClick = onDislike,
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp),
                    colors = ButtonDefaults.outlinedButtonColors(contentColor = Color(0xFFEF4444)),
                    border = BorderStroke(1.dp, Color(0xFFEF4444).copy(alpha = 0.5f)),
                    shape = CutCornerShape(8.dp)
                ) {
                    Icon(Icons.Default.ThumbDown, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(Translator.tr("يحتاج تحسين"), fontFamily = CairoFont, fontWeight = FontWeight.Bold)
