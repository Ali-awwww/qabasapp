    onLike: () -> Unit,
    onDislike: () -> Unit
) {
    GlassmorphicSurface(
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 20.dp),
        shape = CutCornerShape(12.dp),
        backgroundColor = CardSurface.copy(alpha = 0.85f),
        borderColor = Color(0xFF1E293B)
    ) {
        HudCornerDecor(modifier = Modifier.matchParentSize(), color = GoldPrimary.copy(alpha = 0.1f))
        Column(
            modifier = Modifier.padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.Center
            ) {
                Icon(Icons.Default.AutoAwesome, contentDescription = null, tint = GoldPrimary, modifier = Modifier.size(20.dp))
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    Translator.tr("ما رأيك في النتيجة؟"), 
                    color = TextPrimary, 
                    fontFamily = CairoFont, 
                    fontWeight = FontWeight.Bold,
                    fontSize = 16.sp
                )
            }
            
            Text(
                Translator.tr("تقييمك يساعد الذكاء الاصطناعي على فهم أسلوبك وتفضيلاتك للمشاريع القادمة."), 
                color = TextSecondary, 
                fontSize = 13.sp, 
                fontFamily = NotoSansFont, 
                textAlign = TextAlign.Center
            )
            
            Row(
                horizontalArrangement = Arrangement.spacedBy(16.dp),
                modifier = Modifier.fillMaxWidth()
            ) {
                OutlinedButton(
                    onClick = onLike,
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp),
                    colors = ButtonDefaults.outlinedButtonColors(contentColor = Color(0xFF22C55E)),
