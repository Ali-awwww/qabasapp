    fun tr(text: String): String {
        if (currentLanguage == "ar") return text
        return dictionaryEn[text] ?: text
    }

    /**
     * ترجمة قالب فيه قيم وقت التشغيل ({0}، {1}...): استدعاء tr() على
     * نص فيه ${...} أو $var لا يترجم أبداً، لأن المفتاح وقت التشغيل
     * يحمل القيم نفسها فلا يطابق القاموس. في العربية يُعاد القالب
     * نفسه مع القيم (كما كان tr() يعيد النص حرفياً).
     */
    fun trf(template: String, vararg args: Any?): String {
        val resolved = if (currentLanguage == "ar") template
        else dictionaryEn[template] ?: template
        var result = resolved
        args.forEachIndexed { index, arg ->
            result = result.replace("{$index}", arg.toString())
        }
        return result
    }
